"""Q3(c): GMM estimate of gamma with the market and the managed-portfolio moments, W = I.

Implements spec/q3c.md:
- Data (spec/q34_common.md items 6-7): EQ Dataset, R_w,t = exp(re_t), xR_w,t = exp(re_t) - exp(rf_t),
  sample Dec 1940 - Dec 2021; z_{t-1} = E_OS[xR_e] / sigma2_e with the PS1 2e forecast made at
  month t-12 and sigma2_e the variance of R_e over the sample (1/(T-1)); see q34_data.py.
- Moments (2), parameter gamma (1):
      u_1,t = R_w,t^-gamma xR_w,t
      u_2,t = R_w,t^-gamma z_{t-1} xR_w,t
  gamma solves G' E[u(gamma)] = 0 (W = I, A = G'), the first-order condition of
  min E[u]'E[u], with the analytical G_k = -E[ln(R_w) u_k].
- S: Newey-West, Bartlett kernel, NW (1994) automatic lag from 1'u_t, moment series demeaned,
  lag rounded down (see gmm.py). aVar[gamma] = (1/T)(AG)^-1 A S A' (AG)^-1' with A = G'.
- Pricing errors E[eps]_j, j = 1 (xR_w), 2 (managed portfolio), with
  aVar[E[eps]] = (1/T)[I - G(AG)^-1 A] S [I - G(AG)^-1 A]' (rank 1); t_j = E[eps]_j / sqrt(aVar_jj);
  chi2 = E[eps]' aVar^+ E[eps] (Moore-Penrose pseudo-inverse), 1 degree of freedom.

Outputs (output/):
- q3c_gamma_estimate.csv   gamma, its standard error, the NW lag, chi2 statistic and p-value
- q3c_pricing_errors.csv   pricing error and t-statistic of each moment
- q3c_table.tex            LaTeX tabular (input by tex/ps2_solution.tex)

Run from the repository root:  uv run python src/q3c.py
"""

import numpy as np
import pandas as pd
from scipy import stats
from scipy.optimize import brentq

from gmm import gmm_avar, newey_west_s, nw94_lag
from q34_data import load_q3_sample
from sdf import OUTPUT

SEARCH_GRID = np.linspace(-20.0, 60.0, 8001)  # numerical search range for the minimizer
CHI2_DF = 1  # spec: 2 moments - 1 parameter
MOMENT_LABELS = ["Market, $xR_{w,t}$", "Managed portfolio, $z_{t-1} \\cdot xR_{w,t}$"]


def moments(gamma: float, r_w: np.ndarray, x: np.ndarray) -> np.ndarray:
    """T x 2 moment series R_w^-gamma * x, where x stacks xR_w and z_{t-1} xR_w."""
    return (r_w ** (-gamma))[:, None] * x


def g_hat(gamma: float, r_w: np.ndarray, x: np.ndarray) -> np.ndarray:
    """Analytical G (2 x 1): dE[u_k]/dgamma = -E[ln(R_w) u_k]."""
    return -(np.log(r_w)[:, None] * moments(gamma, r_w, x)).mean(axis=0)


def foc(gamma: float, r_w: np.ndarray, x: np.ndarray) -> float:
    return float(g_hat(gamma, r_w, x) @ moments(gamma, r_w, x).mean(axis=0))


def objective(gamma: float, r_w: np.ndarray, x: np.ndarray) -> float:
    e = moments(gamma, r_w, x).mean(axis=0)
    return float(e @ e)


def estimate_gamma(r_w: np.ndarray, x: np.ndarray) -> float:
    """Root of G'E[u] with the smallest E[u]'E[u] (global minimizer on the grid)."""
    values = np.array([foc(c, r_w, x) for c in SEARCH_GRID])
    brackets = np.where(np.sign(values[:-1]) != np.sign(values[1:]))[0]
    if len(brackets) == 0:
        raise ValueError("No solution of the first-order condition on the search grid.")
    roots = [brentq(foc, SEARCH_GRID[i], SEARCH_GRID[i + 1], args=(r_w, x), xtol=1e-14) for i in brackets]
    return min(roots, key=lambda c: objective(c, r_w, x))


def fmt(value: float, digits: int) -> str:
    """Fixed decimals with a typeset minus sign; a value that rounds to zero has no sign."""
    text = f"{value:.{digits}f}"
    if float(text) == 0:
        return text.lstrip("-")
    return text.replace("-", "$-$")


def latex_table(res: dict, months: pd.PeriodIndex) -> str:
    """booktabs tabular: gamma and s.e.; pricing error and t-stat per moment; chi2 test; sample."""
    start, end = (m.strftime("%b %Y") for m in (months[0], months[-1]))
    p = res["p_chi2"]
    lines = [
        "% Generated by src/q3c.py -- do not edit by hand.",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r" & Estimate & s.e. \\",
        r"\midrule",
        rf"$\hat{{\gamma}}$ & {fmt(res['gamma'], 3)} & {fmt(res['se'], 3)} \\",
        r"\midrule",
        r"Pricing error & $\widehat{\mathbb{E}}[\epsilon_j]$ & $t$-stat \\",
        r"\midrule",
    ]
    for label, e, t in zip(MOMENT_LABELS, res["eps"], res["t_eps"]):
        lines.append(rf"{label} & {fmt(e, 4)} & {fmt(t, 2)} \\")
    lines += [
        r"\midrule",
        rf"$\chi^2({CHI2_DF})$ & {fmt(res['chi2'], 2)} & \\",
        rf"$p$-value & {'$<$0.001' if p < 0.001 else fmt(p, 3)} & \\",
        rf"Newey--West lag & {res['lag']} & \\",
        rf"Sample & \multicolumn{{2}}{{c}}{{{start} -- {end} ($T = {len(months)}$)}} \\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    data = load_q3_sample()
    r_w = data["R_w"].to_numpy()
    x = np.column_stack([data["xR_w"], data["z_lag"] * data["xR_w"]])

    gamma = estimate_gamma(r_w, x)
    u = moments(gamma, r_w, x)
    g = g_hat(gamma, r_w, x)[:, None]
    lag = nw94_lag(u)
    avar_gamma, avar_eps = gmm_avar(g.T, g, newey_west_s(u, lag), len(u))
    se = float(np.sqrt(avar_gamma[0, 0]))
    e = u.mean(axis=0)
    t_eps = e / np.sqrt(np.diag(avar_eps))
    chi2 = float(e @ np.linalg.pinv(avar_eps, hermitian=True) @ e)
    res = {"gamma": gamma, "se": se, "lag": lag, "eps": e, "t_eps": t_eps,
           "chi2": chi2, "p_chi2": float(stats.chi2.sf(chi2, CHI2_DF))}

    OUTPUT.mkdir(exist_ok=True)
    pd.DataFrame([{
        "gamma": gamma, "se_gamma": se, "nw_lag": lag,
        "chi2": chi2, "chi2_df": CHI2_DF, "p_value": res["p_chi2"], "sigma2_e": data.attrs["sigma2_e"],
        "sample_start": str(data.index[0]), "sample_end": str(data.index[-1]), "T": len(data),
    }]).to_csv(OUTPUT / "q3c_gamma_estimate.csv", index=False, encoding="utf-8")
    pd.DataFrame({
        "j": [1, 2], "moment": ["xR_w", "z_lag * xR_w"], "pricing_error": e, "t_stat": t_eps,
    }).to_csv(OUTPUT / "q3c_pricing_errors.csv", index=False, encoding="utf-8")
    (OUTPUT / "q3c_table.tex").write_text(latex_table(res, data.index), encoding="utf-8")

    print(f"Sample: {data.index[0]} to {data.index[-1]} (T = {len(data)} months)")
    print(f"gamma = {gamma:.6f} (se {se:.6f}, NW lag {lag}); sigma2_e = {data.attrs['sigma2_e']:.6f}")
    print(f"pricing errors: market {e[0]:.6f} (t {t_eps[0]:.3f}), managed {e[1]:.6f} (t {t_eps[1]:.3f})")
    print(f"chi2({CHI2_DF}) = {chi2:.4f}, p = {res['p_chi2']:.4g}; "
          f"eigenvalues of aVar[E[eps]]: {np.linalg.eigvalsh(avar_eps)}")


if __name__ == "__main__":
    main()
