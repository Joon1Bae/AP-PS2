"""Q3(d): two-step GMM estimate of gamma with the market and managed-portfolio moments.

Implements spec/q3d.md (data, instrument, sample and moments as in Q3(c)):
- Step 1: gamma_1 with W = I (the Q3(c) estimate).
- S_1: Newey-West S at gamma_1 (Bartlett kernel, NW (1994) automatic lag, demeaned moments,
  1/T autocovariances, lag rounded down; see gmm.py).
- Step 2: gamma_2 solves G(gamma)' S_1^-1 E[u(gamma)] = 0, the first-order condition of
  min E[u]' S_1^-1 E[u]; no further iteration.
- Inference: general sandwich formulas with A = G' S_1^-1, G (analytical) at gamma_2, and
  S_2 = Newey-West S re-estimated at gamma_2 (its own automatic lag) in the middle:
      aVar[gamma]  = (1/T)(AG)^-1 A S_2 A' (AG)^-1'
      aVar[E[eps]] = (1/T)[I - G(AG)^-1 A] S_2 [I - G(AG)^-1 A]'
  t_j = E[eps]_j / sqrt(aVar_jj); chi2 = E[eps]' aVar^+ E[eps] (Moore-Penrose), 1 d.f.

Outputs (output/):
- q3d_gamma_estimate.csv   gamma_1, gamma_2, its standard error, the NW lags, chi2 and p-value
- q3d_pricing_errors.csv   pricing error and t-statistic of each moment
- q3d_table.tex            LaTeX tabular (input by tex/ps2_solution.tex)

Run from the repository root:  uv run python src/q3d.py
"""

import numpy as np
import pandas as pd
from scipy import stats
from scipy.optimize import brentq

from gmm import gmm_avar, newey_west_s, nw94_lag
from q34_data import load_q3_sample
from q3c import CHI2_DF, MOMENT_LABELS, SEARCH_GRID, estimate_gamma, fmt, g_hat, moments
from sdf import OUTPUT


def foc_weighted(gamma: float, r_w: np.ndarray, x: np.ndarray, w: np.ndarray) -> float:
    return float(g_hat(gamma, r_w, x) @ w @ moments(gamma, r_w, x).mean(axis=0))


def objective_weighted(gamma: float, r_w: np.ndarray, x: np.ndarray, w: np.ndarray) -> float:
    e = moments(gamma, r_w, x).mean(axis=0)
    return float(e @ w @ e)


def estimate_gamma_weighted(r_w: np.ndarray, x: np.ndarray, w: np.ndarray) -> float:
    """Root of G'W E[u] with the smallest E[u]'W E[u] (global minimizer on the grid)."""
    values = np.array([foc_weighted(c, r_w, x, w) for c in SEARCH_GRID])
    brackets = np.where(np.sign(values[:-1]) != np.sign(values[1:]))[0]
    if len(brackets) == 0:
        raise ValueError("No solution of the first-order condition on the search grid.")
    roots = [
        brentq(foc_weighted, SEARCH_GRID[i], SEARCH_GRID[i + 1], args=(r_w, x, w), xtol=1e-14)
        for i in brackets
    ]
    return min(roots, key=lambda c: objective_weighted(c, r_w, x, w))


def latex_table(res: dict, months: pd.PeriodIndex) -> str:
    """booktabs tabular: gamma_2 and s.e.; pricing error and t-stat per moment; chi2 test; sample."""
    start, end = (m.strftime("%b %Y") for m in (months[0], months[-1]))
    p = res["p_chi2"]
    lines = [
        "% Generated by src/q3d.py -- do not edit by hand.",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r" & Estimate & s.e. \\",
        r"\midrule",
        rf"$\hat{{\gamma}}$ (two-step) & {fmt(res['gamma_2'], 4)} & {fmt(res['se'], 4)} \\",
        r"\midrule",
        r"Pricing error & $\widehat{\mathbb{E}}[\epsilon_j]$ & $t$-stat \\",
        r"\midrule",
    ]
    for label, e, t in zip(MOMENT_LABELS, res["eps"], res["t_eps"]):
        lines.append(rf"{label} & {fmt(e, 4)} & {fmt(t, 2)} \\")
    lines += [
        r"\midrule",
        rf"$\chi^2({CHI2_DF})$ & {fmt(res['chi2'], 2)} & \\",
        rf"$p$-value & {'$<$0.001' if p < 0.001 else fmt(p, 3)} & \\",
        rf"Newey--West lag, $\hat{{S}}_1$ / $\hat{{S}}_2$ & {res['lag_1']} / {res['lag_2']} & \\",
        rf"Sample & \multicolumn{{2}}{{c}}{{{start} -- {end} ($T = {len(months)}$)}} \\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    data = load_q3_sample()
    r_w = data["R_w"].to_numpy()
    x = np.column_stack([data["xR_w"], data["z_lag"] * data["xR_w"]])
    t = len(data)

    gamma_1 = estimate_gamma(r_w, x)
    u_1 = moments(gamma_1, r_w, x)
    lag_1 = nw94_lag(u_1)
    w = np.linalg.inv(newey_west_s(u_1, lag_1))

    gamma_2 = estimate_gamma_weighted(r_w, x, w)
    u_2 = moments(gamma_2, r_w, x)
    lag_2 = nw94_lag(u_2)
    s_2 = newey_west_s(u_2, lag_2)
    g = g_hat(gamma_2, r_w, x)[:, None]
    a = g.T @ w
    avar_gamma, avar_eps = gmm_avar(a, g, s_2, t)

    e = u_2.mean(axis=0)
    t_eps = e / np.sqrt(np.diag(avar_eps))
    chi2 = float(e @ np.linalg.pinv(avar_eps, hermitian=True) @ e)
    res = {"gamma_2": gamma_2, "se": float(np.sqrt(avar_gamma[0, 0])), "lag_1": lag_1, "lag_2": lag_2,
           "eps": e, "t_eps": t_eps, "chi2": chi2, "p_chi2": float(stats.chi2.sf(chi2, CHI2_DF))}

    OUTPUT.mkdir(exist_ok=True)
    pd.DataFrame([{
        "gamma_1": gamma_1, "gamma_2": gamma_2, "se_gamma_2": res["se"],
        "nw_lag_S1": lag_1, "nw_lag_S2": lag_2,
        "chi2": chi2, "chi2_df": CHI2_DF, "p_value": res["p_chi2"],
        "sample_start": str(data.index[0]), "sample_end": str(data.index[-1]), "T": t,
    }]).to_csv(OUTPUT / "q3d_gamma_estimate.csv", index=False, encoding="utf-8")
    pd.DataFrame({
        "j": [1, 2], "moment": ["xR_w", "z_lag * xR_w"], "pricing_error": e, "t_stat": t_eps,
    }).to_csv(OUTPUT / "q3d_pricing_errors.csv", index=False, encoding="utf-8")
    (OUTPUT / "q3d_table.tex").write_text(latex_table(res, data.index), encoding="utf-8")

    print(f"Sample: {data.index[0]} to {data.index[-1]} (T = {t} months)")
    print(f"step 1: gamma_1 = {gamma_1:.6f}, NW lag for S_1 = {lag_1}")
    print(f"step 2: gamma_2 = {gamma_2:.6f} (se {res['se']:.6f}), NW lag for S_2 = {lag_2}")
    print(f"pricing errors: market {e[0]:.6f} (t {t_eps[0]:.3f}), managed {e[1]:.6f} (t {t_eps[1]:.3f})")
    print(f"chi2({CHI2_DF}) = {chi2:.4f}, p = {res['p_chi2']:.4g}; "
          f"eigenvalues of aVar[E[eps]]: {np.linalg.eigvalsh(avar_eps)}")


if __name__ == "__main__":
    main()
