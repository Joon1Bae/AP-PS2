"""Q3(b): GMM estimate of gamma from E[R_w,t^(-gamma) xR_w,t] = 0.

Implements spec/q3b.md:
- Data: EQ Dataset, R_w,t = exp(re_t), R_f,t = exp(rf_t), xR_w,t = R_w,t - R_f,t;
  two samples (spec/q34_common.md item 6): (1) Common Dec 1940 - Dec 2021, (2) Max Dec 1927 - Dec 2021.
- One moment, one parameter. gamma solves G * E[R_w^-gamma xR_w] = 0 with the analytical
  G = dE[R_w^-gamma xR_w]/dgamma = -E[ln(R_w) R_w^-gamma xR_w] (footnote 5), i.e. the
  minimizer of E[R_w^-gamma xR_w]^2.
- S: Newey-West, Bartlett kernel, NW (1994) automatic lag on the demeaned moment series,
  rounded down (spec/q3b.md decision 3; see gmm.py). aVar[gamma] = (1/T)(AG)^-1 A S A' (AG)^-1',
  which with one moment and one parameter is S / (T G^2).

Outputs (output/):
- q3b_gamma_estimate.csv   gamma, its standard error, the NW lag, the moment and G at gamma
- q3b_table.tex            the same as a LaTeX tabular (input by tex/ps2_solution.tex)

Run from the repository root:  uv run python src/q3b.py
"""

import numpy as np
import pandas as pd
from scipy.optimize import brentq

from gmm import gmm_avar, newey_west_s, nw94_lag
from q34_data import EQ_START, Q3_SAMPLE_START, VERSIONS, load_eq, restrict
from sdf import OUTPUT

SEARCH_GRID = np.linspace(-20.0, 60.0, 8001)  # numerical search range for the minimizer


def moment(gamma: float, r_w: np.ndarray, xr_w: np.ndarray) -> float:
    return float(np.mean(r_w ** (-gamma) * xr_w))


def g_hat(gamma: float, r_w: np.ndarray, xr_w: np.ndarray) -> float:
    """Analytical G = -E[ln(R_w) R_w^-gamma xR_w]."""
    return float(-np.mean(np.log(r_w) * r_w ** (-gamma) * xr_w))


def estimate_gamma(r_w: np.ndarray, xr_w: np.ndarray) -> float:
    """Root of G * E[moment] with the smallest squared moment (global minimizer on the grid)."""
    foc = np.array([g_hat(c, r_w, xr_w) * moment(c, r_w, xr_w) for c in SEARCH_GRID])
    brackets = np.where(np.sign(foc[:-1]) != np.sign(foc[1:]))[0]
    if len(brackets) == 0:
        raise ValueError("No solution of the first-order condition on the search grid.")
    roots = [
        brentq(lambda c: g_hat(c, r_w, xr_w) * moment(c, r_w, xr_w),
               SEARCH_GRID[i], SEARCH_GRID[i + 1], xtol=1e-14)
        for i in brackets
    ]
    return min(roots, key=lambda c: moment(c, r_w, xr_w) ** 2)


def latex_table(res: dict) -> str:
    """One column per sample version: gamma, (s.e.), NW lag, sample, T."""
    keys = list(VERSIONS)
    def row(label, cells):
        return label + " & " + " & ".join(cells) + r" \\"
    return "\n".join([
        "% Generated by src/q3b.py -- do not edit by hand.",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        row("", [VERSIONS[k] for k in keys]),
        r"\midrule",
        row(r"$\hat{\gamma}$", [f"{res[k]['gamma']:.4f}" for k in keys]),
        row("", [f"({res[k]['se']:.4f})" for k in keys]),
        r"\midrule",
        row("Newey--West lag", [str(res[k]["lag"]) for k in keys]),
        row("Sample", [res[k]["months"][0].strftime("%b %Y") + " -- " + res[k]["months"][-1].strftime("%b %Y") for k in keys]),
        row("$T$ (months)", [str(len(res[k]["months"])) for k in keys]),
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ])


def run(eq: pd.DataFrame) -> dict:
    r_w = eq["R_w"].to_numpy()
    xr_w = eq["xR_w"].to_numpy()
    gamma = estimate_gamma(r_w, xr_w)
    u = (r_w ** (-gamma) * xr_w)[:, None]
    g = np.array([[g_hat(gamma, r_w, xr_w)]])
    lag = nw94_lag(u)
    avar_gamma, _ = gmm_avar(g.T, g, newey_west_s(u, lag), len(u))
    return {"gamma": gamma, "se": float(np.sqrt(avar_gamma[0, 0])), "lag": lag,
            "moment": moment(gamma, r_w, xr_w), "G": g_hat(gamma, r_w, xr_w), "months": eq.index}


def main() -> None:
    eq_all = load_eq()
    starts = {"common": Q3_SAMPLE_START, "max": EQ_START}
    res = {k: run(restrict(eq_all, starts[k])) for k in VERSIONS}

    OUTPUT.mkdir(exist_ok=True)
    pd.DataFrame([{
        "version": k, "gamma": r["gamma"], "se_gamma": r["se"], "nw_lag": r["lag"],
        "moment_at_gamma": r["moment"], "G_at_gamma": r["G"],
        "sample_start": str(r["months"][0]), "sample_end": str(r["months"][-1]), "T": len(r["months"]),
    } for k, r in res.items()]).to_csv(OUTPUT / "q3b_gamma_estimate.csv", index=False, encoding="utf-8")
    (OUTPUT / "q3b_table.tex").write_text(latex_table(res), encoding="utf-8")

    for k, r in res.items():
        print(f"{VERSIONS[k]:11s} {r['months'][0]} to {r['months'][-1]} (T = {len(r['months'])}): "
              f"gamma = {r['gamma']:.6f} (se {r['se']:.6f}, NW lag {r['lag']}); moment {r['moment']:.2e}")


if __name__ == "__main__":
    main()
