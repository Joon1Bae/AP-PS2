"""Q2(c): SDF M* = a - b'xR that prices the excess returns of the 20 BE/ME + momentum deciles.

Implements spec/q2c.md:
- Data: the Q2(a) and Q2(b) excess returns (monthly value-weighted "Lo 10" ... "Hi 10" and
  "Lo PRIOR" ... "Hi PRIOR", RF from F-F_Research_Data_Factors.csv), July 1927 to the latest
  month, in decimal units. Portfolio index j = 1..20: 1 = Lo 10, ..., 10 = Hi 10,
  11 = Lo PRIOR, ..., 20 = Hi PRIOR.
- (a, b) solve the two sample-moment equations of the spec (E[.] = time average):
      a - b' E[xR] = 1              (normalization E[M*] = 1)
      a E[xR] - E[xR xR'] b = 0     (E[M* xR] = 0 for j = 1..20)
- Scatterplot: decile 1..10 on the x-axis, b on the y-axis; blue for j = 1..10 (BE/ME),
  red for j = 11..20 (momentum).
- Sharpe ratios of xR* = b'xR for the SDFs of Q2(a), Q2(b) and Q2(c):
  SR(xR*) = E[xR*] / sigma(xR*), from the monthly series.

Outputs (output/):
- q2c_b_scatter.pdf         scatterplot of b by decile, colored by sorting variable
- q2c_sdf_coefficients.csv  estimated a and b (j, sort, decile)
- q2c_sharpe_ratios.csv     Sharpe ratios of xR* for Q2(a), Q2(b), Q2(c)
- q2c_sharpe_ratios.tex     the same values as LaTeX macros (QtwocSRa, QtwocSRb, QtwocSRc, QtwocT)

Run from the repository root:  uv run python src/q2c.py
"""

import pandas as pd

from q2a import load_bm_excess_returns
from q2b import load_mom_excess_returns
from sdf import OUTPUT, plot_b_groups, print_summary, sharpe_ratio, solve_sdf

BM_COLOR = "#2a78d6"   # blue: BE/ME deciles
MOM_COLOR = "#e34948"  # red: momentum deciles


def main() -> None:
    xr_bm = load_bm_excess_returns()
    xr_mom = load_mom_excess_returns()
    # The spec has no rule for aligning different samples, so require identical months.
    if not xr_bm.index.equals(xr_mom.index):
        raise ValueError("BE/ME and momentum samples differ; the spec needs a rule to align them.")
    xr = pd.concat([xr_bm, xr_mom], axis=1)  # columns j = 1..10 BE/ME, 11..20 momentum

    a, b = solve_sdf(xr)
    b_bm, b_mom = b.iloc[:10], b.iloc[10:]

    OUTPUT.mkdir(exist_ok=True)
    pd.DataFrame({
        "parameter": ["a"] + ["b"] * len(b),
        "j": [pd.NA] + list(range(1, len(b) + 1)),
        "sort": [pd.NA] + ["BE/ME"] * 10 + ["Momentum"] * 10,
        "decile": [pd.NA] + list(range(1, 11)) * 2,
        "portfolio": [pd.NA] + list(b.index),
        "value": [a] + list(b.to_numpy()),
    }).to_csv(OUTPUT / "q2c_sdf_coefficients.csv", index=False, encoding="utf-8")

    plot_b_groups(
        [
            (b_bm, BM_COLOR, "o", "Book-to-market (BM)"),
            (b_mom, MOM_COLOR, "s", "Momentum (MOM)"),
        ],
        OUTPUT / "q2c_b_scatter.pdf",
        xlabel="Portfolio decile (1 = Lo, 10 = Hi)",
    )
    print_summary(xr, a, b)

    # Sharpe ratios of xR* = b'xR for the SDFs of Q2(a), Q2(b) and Q2(c).
    _, b_2a = solve_sdf(xr_bm)
    _, b_2b = solve_sdf(xr_mom)
    sharpe = {
        "2a (BM, 10 portfolios)": sharpe_ratio(xr_bm, b_2a),
        "2b (MOM, 10 portfolios)": sharpe_ratio(xr_mom, b_2b),
        "2c (BM + MOM, 20 portfolios)": sharpe_ratio(xr, b),
    }
    pd.DataFrame({"sdf": list(sharpe), "monthly_sharpe_ratio": list(sharpe.values())}).to_csv(
        OUTPUT / "q2c_sharpe_ratios.csv", index=False, encoding="utf-8"
    )
    sr_a, sr_b, sr_c = sharpe.values()
    (OUTPUT / "q2c_sharpe_ratios.tex").write_text(
        "% Generated by src/q2c.py -- do not edit by hand.\n"
        f"\\newcommand{{\\QtwocSRa}}{{{sr_a:.3f}}}\n"
        f"\\newcommand{{\\QtwocSRb}}{{{sr_b:.3f}}}\n"
        f"\\newcommand{{\\QtwocSRc}}{{{sr_c:.3f}}}\n"
        f"\\newcommand{{\\QtwocT}}{{{len(xr)}}}\n",
        encoding="utf-8",
    )
    for name, value in sharpe.items():
        print(f"Monthly Sharpe ratio of xR*, {name} = {value:.6f}")


if __name__ == "__main__":
    main()
