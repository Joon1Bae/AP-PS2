"""LaTeX layout for the 21-asset tables of Q3(e) and Q4(b)-(e) (spec/solution_format.md, "Long tables").

Panel A: parameter estimate(s) and standard error(s).
Panel B: pricing errors (or alphas) with t-stats, book-to-market and momentum deciles side by side
         (rows = deciles 1-10), the market xR_{w,t} in a separate row below; one block per estimate.
Panel C: joint test, Newey-West lag(s), sample.
Numbers are aligned at the decimal point with siunitx S columns.
"""

import math

COLUMNS = r"l S[table-format=-1.4] S[table-format=-1.2] S[table-format=-1.4] S[table-format=-1.2]"


def num(value: float, digits: int) -> str:
    """Plain number for an S column; '--' (braced) when undefined; no sign on a rounded zero."""
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "{--}"
    text = f"{value:.{digits}f}"
    return text.lstrip("-") if float(text) == 0 else text


def text_cell(content: str, span: int = 1) -> str:
    return rf"\multicolumn{{{span}}}{{c}}{{{content}}}"


def panel_title(title: str) -> str:
    return rf"\multicolumn{{5}}{{l}}{{\textit{{{title}}}}} \\"


def long_table(source: str, panel_a: dict, panel_b: dict, panel_c: dict, sample: str) -> str:
    """Build the tabular.

    panel_a: {"title", "header": (h1, h2), "rows": [(label, cell1, cell2), ...]}; each cell spans two columns.
    panel_b: {"title", "stat": column header for the estimate (e.g. pricing error), "blocks":
              [(block title or None, values[21], t_stats[21]), ...]}; assets 1-10 BM, 11-20 MOM, 21 market.
    panel_c: {"title", "header": (four header cells), "rows": [(label, four cells), ...]}.
    """
    lines = [
        f"% Generated by {source} -- do not edit by hand.",
        rf"\begin{{tabular}}{{{COLUMNS}}}",
        r"\toprule",
        panel_title(panel_a["title"]),
        " & " + " & ".join(text_cell(h, 2) for h in panel_a["header"]) + r" \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
    ]
    for label, c1, c2 in panel_a["rows"]:
        lines.append(rf"{label} & {text_cell(c1, 2)} & {text_cell(c2, 2)} \\")

    lines += [
        r"\midrule",
        panel_title(panel_b["title"]),
        r" & " + text_cell("Book-to-market", 2) + " & " + text_cell("Momentum", 2) + r" \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Decile & " + " & ".join([text_cell(panel_b["stat"]), text_cell("$t$-stat")] * 2) + r" \\",
    ]
    for b, (title, values, t_stats) in enumerate(panel_b["blocks"]):
        lines.append(r"\addlinespace" if b else r"\midrule")
        if title:
            lines.append(rf"\multicolumn{{5}}{{l}}{{{title}}} \\")
        for d in range(10):
            label = {0: "1 (Lo)", 9: "10 (Hi)"}.get(d, str(d + 1))
            lines.append(
                rf"\quad {label} & {num(values[d], 4)} & {num(t_stats[d], 2)} & "
                rf"{num(values[10 + d], 4)} & {num(t_stats[10 + d], 2)} \\"
            )
        lines.append(rf"\quad Market, $xR_{{w,t}}$ & {num(values[20], 4)} & {num(t_stats[20], 2)} & & \\")

    lines += [
        r"\midrule",
        panel_title(panel_c["title"]),
        " & " + " & ".join(text_cell(h) for h in panel_c["header"]) + r" \\",
        r"\cmidrule(lr){2-5}",
    ]
    for label, *cells in panel_c["rows"]:
        lines.append(f"{label} & " + " & ".join(text_cell(c) for c in cells) + r" \\")
    lines += [
        r"\addlinespace",
        rf"Sample & {text_cell(sample, 4)} \\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    return "\n".join(lines)


def p_text(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def sample_text(months) -> str:
    start, end = (m.strftime("%b %Y") for m in (months[0], months[-1]))
    return f"{start} -- {end} ($T = {len(months)}$)"
