"""Q2(b): SDF M* = a - b'xR that prices the excess returns of the 10 momentum deciles.

Implements spec/q2b.md:
- Data: RF from F-F_Research_Data_Factors.csv; "Lo PRIOR" ... "Hi PRIOR" from the
  monthly value-weighted block of 10_Portfolios_Prior_12_2.csv.
- Sample: July 1927 to the latest month in the data.
- xR = (R_p - RF) / 100, i.e. excess returns in decimal units.
- (a, b) solve the two sample-moment equations of the spec (E[.] = time average):
      a - b' E[xR] = 1              (normalization E[M*] = 1)
      a E[xR] - E[xR xR'] b = 0     (E[M* xR] = 0 for each decile)
- Correlation: recover M1 = a1 - b1'xR (BE/ME, Q2(a)) and M2 = a2 - b2'xR (momentum)
  month by month and compute their (Pearson) correlation.

Outputs (output/):
- q2b_momentum_stats.csv / .tex  adjacent-decile correlation range, mean excess return of decile 10
                                minus decile 1 (percent per month), corr(decile 1, decile 10); macros
                                QtwobCorrMin, QtwobCorrMax, QtwobSpread, QtwobCorrExt (interpretation)
- q2b_b_scatter.pdf         scatterplot of b by momentum decile
- q2b_sdf_coefficients.csv  estimated a and b
- q2b_sdf_correlation.csv   correlation between M*_t from Q2(a) and Q2(b)
- q2b_sdf_correlation.tex   the same value as LaTeX macros (QtwobCorr, QtwobT)

Run from the repository root:  uv run python src/q2b.py
"""

import pandas as pd

from q2a import load_bm_excess_returns
from sdf import (
    OUTPUT, load_excess_returns, plot_b, print_summary, save_coefficients, sdf_series, solve_sdf,
)

DECILES = [
    "Lo PRIOR", "PRIOR 2", "PRIOR 3", "PRIOR 4", "PRIOR 5",
    "PRIOR 6", "PRIOR 7", "PRIOR 8", "PRIOR 9", "Hi PRIOR",
]
SAMPLE_START = pd.Period("1927-07", freq="M")


def load_mom_excess_returns() -> pd.DataFrame:
    """Monthly decimal excess returns of the 10 value-weighted momentum deciles."""
    return load_excess_returns(
        "10_Portfolios_Prior_12_2.csv", "Value Weight Returns -- Monthly", DECILES, SAMPLE_START
    )


def main() -> None:
    xr = load_mom_excess_returns()
    a, b = solve_sdf(xr)

    OUTPUT.mkdir(exist_ok=True)
    save_coefficients(a, b, OUTPUT / "q2b_sdf_coefficients.csv")
    plot_b(b, OUTPUT / "q2b_b_scatter.pdf", xlabel="Momentum decile (1 = Lo PRIOR, 10 = Hi PRIOR)")
    print_summary(xr, a, b)

    xr_bm = load_bm_excess_returns()
    a_bm, b_bm = solve_sdf(xr_bm)
    m_bm = sdf_series(xr_bm, a_bm, b_bm)
    m_mom = sdf_series(xr, a, b)
    # The spec has no rule for aligning different samples, so require identical months.
    if not m_bm.index.equals(m_mom.index):
        raise ValueError("Q2(a) and Q2(b) samples differ; the spec needs a rule to align them.")
    correlation = m_mom.corr(m_bm, method="pearson")

    pd.DataFrame({
        "statistic": ["corr(M*_2a, M*_2b)", "T", "sample_start", "sample_end"],
        "value": [correlation, len(m_mom), str(m_mom.index[0]), str(m_mom.index[-1])],
    }).to_csv(OUTPUT / "q2b_sdf_correlation.csv", index=False, encoding="utf-8")
    # LaTeX macros so tex/ps2_solution.tex always shows the value from this run.
    (OUTPUT / "q2b_sdf_correlation.tex").write_text(
        "% Generated by src/q2b.py -- do not edit by hand.\n"
        f"\\newcommand{{\\QtwobCorr}}{{{correlation:.3f}}}\n"
        f"\\newcommand{{\\QtwobT}}{{{len(m_mom)}}}\n",
        encoding="utf-8",
    )
    print(f"Correlation between M*_t from Q2(a) and Q2(b) = {correlation:.6f}")

    # Statistics for the interpretation (spec/q2b.md): adjacent-decile correlations, the mean excess
    # return of decile 10 minus decile 1 (percent per month), and the correlation of deciles 1 and 10.
    corr = xr.corr()
    adjacent = [corr.iloc[i, i + 1] for i in range(len(xr.columns) - 1)]
    stats = {
        "CorrMin": min(adjacent), "CorrMax": max(adjacent),
        "Spread": 100 * (xr["Hi PRIOR"].mean() - xr["Lo PRIOR"].mean()),
        "CorrExt": corr.loc["Lo PRIOR", "Hi PRIOR"],
    }
    pd.DataFrame({"statistic": list(stats), "value": list(stats.values())}).to_csv(
        OUTPUT / "q2b_momentum_stats.csv", index=False, encoding="utf-8"
    )
    (OUTPUT / "q2b_momentum_stats.tex").write_text(
        "% Generated by src/q2b.py -- do not edit by hand.\n"
        + "".join(f"\\newcommand{{\\Qtwob{k}}}{{{v:.2f}}}\n" for k, v in stats.items()),
        encoding="utf-8",
    )
    print("Momentum statistics:", {k: round(v, 4) for k, v in stats.items()})


if __name__ == "__main__":
    main()
