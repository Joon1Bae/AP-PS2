"""Q2(d): pricing errors of the 20 BE/ME + momentum deciles under the SDFs of Q2(a)-(c).

Implements spec/q2d.md:
- Data and xR as in Q2(a)-(c): monthly value-weighted deciles, RF from
  F-F_Research_Data_Factors.csv, July 1927 to the latest month, decimal units.
  Portfolio index j = 1..20: 1 = Lo 10, ..., 10 = Hi 10, 11 = Lo PRIOR, ..., 20 = Hi PRIOR.
- Models: (a1, b1) from the 10 BE/ME deciles (Q2(a)), (a2, b2) from the 10 momentum deciles
  (Q2(b)), (a3, b3) from all 20 (Q2(c)); each M_t = a - b'xR_t.
- For all j = 1..20 under each of the three models:
      alpha_j = E[xR_j] - Cov(-M, xR_j),
  with E[.] the time average and Cov(-M, xR_j) = 1/T sum_t (-M_t + Mbar)(xR_j,t - xRbar_j).

Outputs (output/):
- q2d_pricing_errors.csv        alpha_j under each model (decimal, per month)
- q2d_pricing_errors_table.tex  the same values as a LaTeX tabular (input by tex/ps2_solution.tex)

Run from the repository root:  uv run python src/q2d.py
"""

import pandas as pd

from q2a import load_bm_excess_returns
from q2b import load_mom_excess_returns
from sdf import OUTPUT, pricing_errors, sdf_series, solve_sdf

MODELS = {"2a": "BM", "2b": "MOM", "2c": "BM + MOM"}


def fmt(value: float) -> str:
    text = f"{value:.4f}"
    return "0.0000" if text == "-0.0000" else text


def latex_table(table: pd.DataFrame) -> str:
    """booktabs/siunitx tabular: one row per portfolio, one column per SDF, BM and MOM panels."""
    lines = [
        "% Generated by src/q2d.py -- do not edit by hand.",
        r"\begin{tabular}{l" + " S[table-format=-1.4]" * len(MODELS) + "}",
        r"\toprule",
        r" & \multicolumn{3}{c}{SDF $M^*_t$ estimated in} \\",
        r"\cmidrule(lr){2-4}",
        "Portfolio & " + " & ".join(f"{{{q}) {name}}}" for q, name in MODELS.items()) + r" \\",
        r"\midrule",
    ]
    panels = [
        ("BE/ME", r"\textit{Panel A: book-to-market deciles}", "Lo 10", "Hi 10"),
        ("Momentum", r"\textit{Panel B: momentum deciles}", "Lo PRIOR", "Hi PRIOR"),
    ]
    for i, (sort, title, lo, hi) in enumerate(panels):
        if i:
            lines.append(r"\addlinespace")
        lines.append(rf"\multicolumn{{4}}{{l}}{{{title}}} \\")
        for _, row in table[table["sort"] == sort].iterrows():
            label = {1: f"1 ({lo})", 10: f"10 ({hi})"}.get(row["decile"], str(row["decile"]))
            values = " & ".join(fmt(row[f"alpha_{q}"]) for q in MODELS)
            lines.append(rf"\quad {label} & {values} \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def main() -> None:
    xr_bm = load_bm_excess_returns()
    xr_mom = load_mom_excess_returns()
    # The spec has no rule for aligning different samples, so require identical months.
    if not xr_bm.index.equals(xr_mom.index):
        raise ValueError("BE/ME and momentum samples differ; the spec needs a rule to align them.")
    xr_all = pd.concat([xr_bm, xr_mom], axis=1)  # j = 1..10 BE/ME, 11..20 momentum

    table = pd.DataFrame({
        "j": range(1, 21),
        "sort": ["BE/ME"] * 10 + ["Momentum"] * 10,
        "decile": list(range(1, 11)) * 2,
        "portfolio": list(xr_all.columns),
    })
    for q, xr_model in {"2a": xr_bm, "2b": xr_mom, "2c": xr_all}.items():
        a, b = solve_sdf(xr_model)
        m = sdf_series(xr_model, a, b)
        table[f"alpha_{q}"] = pricing_errors(xr_all, m).to_numpy()

    OUTPUT.mkdir(exist_ok=True)
    table.to_csv(OUTPUT / "q2d_pricing_errors.csv", index=False, encoding="utf-8")
    (OUTPUT / "q2d_pricing_errors_table.tex").write_text(latex_table(table), encoding="utf-8")

    print(f"Sample: {xr_all.index[0]} to {xr_all.index[-1]} (T = {len(xr_all)} months)")
    print("Pricing errors alpha_j (decimal, per month):")
    print(table.drop(columns="sort").to_string(index=False, float_format=lambda v: f"{v:.6f}"))


if __name__ == "__main__":
    main()
