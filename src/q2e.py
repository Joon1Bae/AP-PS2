"""Q2(e): out-of-sample pricing errors of the 20 BE/ME + momentum deciles.

Implements spec/q2e.md:
- Data as in Q2(c): monthly value-weighted deciles, RF from F-F_Research_Data_Factors.csv.
  Portfolio index j = 1..20: 1 = Lo 10, ..., 10 = Hi 10, 11 = Lo PRIOR, ..., 20 = Hi PRIOR.
- Units: percent per month (spec Additional Decision 2), i.e. xR = R_p - RF as given in the
  files. M_t is unchanged by this scaling (b scales by 1/100, a does not change), so the
  percent alphas are exactly 100 times the decimal ones.
- (a^, b^) solve the spec's two moment equations on July 1927 to December 1989, using all 20
  portfolios (the Q2(c) construction).
- Out of sample, January 1990 to the latest month:
      M_OS,t  = a^ - b^'xR_t
      alpha_j = E[xR_j] - Cov(-M_OS, xR_j),
  with E[.] the time average and Cov(-M_OS, xR_j) = 1/T sum_t (-M_t + Mbar)(xR_j,t - xRbar_j),
  all over the out-of-sample months.

Outputs (output/):
- q2e_sdf_coefficients.csv      a^ and b^ (b^ in units of 1/percent)
- q2e_pricing_errors.csv        alpha_OS,j and the in-sample alpha_j of the BM + MOM SDF on the full
                                sample (Q2(d), spec item 8), percent per month, full precision
- q2e_pricing_errors_table.tex  the same values as a LaTeX tabular (input by tex/ps2_solution.tex)
- q2e_sharpe_ratios.csv / .tex Sharpe ratio of xR* = b'xR with b fixed at its Jul 1927 - Dec 1989
                                estimate, in sample (estimation period) and out of sample (Jan 1990 on);
                                macros QtwoeSRis, QtwoeSRos (2 decimals); also the min and max
                                out-of-sample pricing errors, QtwoeAlphaMin, QtwoeAlphaMax (percent)
- q2e_samples.tex               LaTeX macros for the two samples (QtwoeTis, QtwoeTos, QtwoeEnd)

Run from the repository root:  uv run python src/q2e.py
"""

import pandas as pd

from q2a import load_bm_excess_returns
from q2b import load_mom_excess_returns
from sdf import OUTPUT, pricing_errors, save_coefficients, sdf_series, sharpe_ratio, solve_sdf

ESTIMATION_END = pd.Period("1989-12", freq="M")
OOS_START = pd.Period("1990-01", freq="M")


def fmt(value: float) -> str:
    """Alpha in percent with 3 decimals, as in Q2(d)."""
    text = f"{value:.3f}"
    return text.lstrip("-") if float(text) == 0 else text


def latex_table(table: pd.DataFrame, period_is: str, period_os: str) -> str:
    """booktabs/siunitx tabular: in-sample (Q2(d)) and out-of-sample (Q2(e)) pricing errors of the
    BM + MOM SDF, one row per portfolio, BM and MOM panels."""
    lines = [
        "% Generated by src/q2e.py -- do not edit by hand. Values in percent per month.",
        r"\begin{tabular}{l S[table-format=-1.3] S[table-format=-1.3]}",
        r"\toprule",
        r" & \multicolumn{2}{c}{BM + MOM SDF} \\",
        r"\cmidrule(lr){2-3}",
        r"Portfolio & {In-sample (Q2(d))} & {Out-of-sample (Q2(e))} \\",
        r" & {$\hat{\alpha}_p$} & {$\hat{\alpha}_{OS,p}$} \\",
        rf" & {{\footnotesize {period_is}}} & {{\footnotesize {period_os}}} \\",
        r"\midrule",
    ]
    panels = [
        ("BE/ME", r"\textit{Panel A: book-to-market deciles}", "Lo 10", "Hi 10"),
        ("Momentum", r"\textit{Panel B: momentum deciles}", "Lo PRIOR", "Hi PRIOR"),
    ]
    for i, (sort, title, lo, hi) in enumerate(panels):
        if i:
            lines.append(r"\addlinespace")
        lines.append(rf"\multicolumn{{3}}{{l}}{{{title}}} \\")
        for _, row in table[table["sort"] == sort].iterrows():
            label = {1: f"1 ({lo})", 10: f"10 ({hi})"}.get(row["decile"], str(row["decile"]))
            lines.append(rf"\quad {label} & {fmt(row['alpha_is'])} & {fmt(row['alpha_os'])} \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def main() -> None:
    xr_bm = load_bm_excess_returns()
    xr_mom = load_mom_excess_returns()
    # The spec has no rule for aligning different samples, so require identical months.
    if not xr_bm.index.equals(xr_mom.index):
        raise ValueError("BE/ME and momentum samples differ; the spec needs a rule to align them.")
    # j = 1..10 BE/ME, 11..20 momentum; loaders return decimals, the spec asks for percent.
    xr_all = 100.0 * pd.concat([xr_bm, xr_mom], axis=1)

    xr_in = xr_all.loc[:ESTIMATION_END]
    xr_os = xr_all.loc[OOS_START:]
    a, b = solve_sdf(xr_in)
    m_os = sdf_series(xr_os, a, b)

    # In-sample comparison (spec item 8): the BM + MOM SDF of Q2(c)/(d) on the full sample.
    a_full, b_full = solve_sdf(xr_all)
    alpha_is = pricing_errors(xr_all, sdf_series(xr_all, a_full, b_full))

    table = pd.DataFrame({
        "j": range(1, 21),
        "sort": ["BE/ME"] * 10 + ["Momentum"] * 10,
        "decile": list(range(1, 11)) * 2,
        "portfolio": list(xr_all.columns),
        "alpha_is": alpha_is.to_numpy(),
        "alpha_os": pricing_errors(xr_os, m_os).to_numpy(),
    })
    span = lambda idx: f"{idx[0].strftime('%b %Y')} -- {idx[-1].strftime('%b %Y')}"

    OUTPUT.mkdir(exist_ok=True)
    save_coefficients(a, b, OUTPUT / "q2e_sdf_coefficients.csv")
    table.to_csv(OUTPUT / "q2e_pricing_errors.csv", index=False, encoding="utf-8")
    (OUTPUT / "q2e_pricing_errors_table.tex").write_text(latex_table(table, span(xr_all.index), span(xr_os.index)), encoding="utf-8")
    # Sharpe ratio of xR* = b'xR with b fixed at the estimation-sample value (spec interpretation note).
    sr = {"in_sample": sharpe_ratio(xr_in, b), "out_of_sample": sharpe_ratio(xr_os, b)}
    pd.DataFrame([{
        "statistic": k, "monthly_sharpe_ratio": v,
        "sample_start": str(x.index[0]), "sample_end": str(x.index[-1]), "T": len(x),
    } for (k, v), x in zip(sr.items(), (xr_in, xr_os))]).to_csv(
        OUTPUT / "q2e_sharpe_ratios.csv", index=False, encoding="utf-8")
    (OUTPUT / "q2e_sharpe_ratios.tex").write_text(
        "% Generated by src/q2e.py -- do not edit by hand. Monthly Sharpe ratios of xR* (b fixed).\n"
        f"\\newcommand{{\\QtwoeSRis}}{{{sr['in_sample']:.2f}}}\n"
        f"\\newcommand{{\\QtwoeSRos}}{{{sr['out_of_sample']:.2f}}}\n"
        f"\\newcommand{{\\QtwoeAlphaMin}}{{{table['alpha_os'].min():.2f}}}\n"
        f"\\newcommand{{\\QtwoeAlphaMax}}{{{table['alpha_os'].max():.2f}}}\n",
        encoding="utf-8",
    )

    (OUTPUT / "q2e_samples.tex").write_text(
        "% Generated by src/q2e.py -- do not edit by hand.\n"
        f"\\newcommand{{\\QtwoeTis}}{{{len(xr_in)}}}\n"
        f"\\newcommand{{\\QtwoeTos}}{{{len(xr_os)}}}\n"
        f"\\newcommand{{\\QtwoeEnd}}{{{xr_os.index[-1].strftime('%B %Y')}}}\n",
        encoding="utf-8",
    )

    print(f"Estimation sample: {xr_in.index[0]} to {xr_in.index[-1]} (T = {len(xr_in)} months)")
    print(f"Out-of-sample:     {xr_os.index[0]} to {xr_os.index[-1]} (T = {len(xr_os)} months)")
    print(f"a = {a:.6f}; mean of M_OS = {m_os.mean():.6f}")
    print(f"Out-of-sample pricing errors: min {table['alpha_os'].min():.4f}, max {table['alpha_os'].max():.4f}, "
          f"all positive: {bool((table['alpha_os'] > 0).all())}")
    print(f"Sharpe ratio of xR* (b fixed): in sample {sr['in_sample']:.6f}, out of sample {sr['out_of_sample']:.6f}")
    print("Out-of-sample pricing errors alpha_OS,j (percent per month):")
    print(table.drop(columns="sort").to_string(index=False, float_format=lambda v: f"{v:.4f}"))


if __name__ == "__main__":
    main()
